#!/usr/bin/env python3
"""Scan C sources for FUN_1000_xxxx definitions and produce full prototypes.

K&R definitions (the generated game code) get prototypes with promoted
parameter types (which is what a K&R definition is compatible with); ANSI
definitions (hand written code) get their exact parameter types.  With one
consistent set of prototypes every call is type checked, which WebAssembly
requires (calling a function with a different signature traps)."""
import re
import sys

NARROW = {"uint8_t", "int8_t", "uint16_t", "int16_t", "char", "bool"}

# return type (possibly on the previous line), name, parameter list, then
# either K&R declarations or the opening brace
DEF_RE = re.compile(
    r"^([A-Za-z_][\w \*]*?)\s*\b(FUN_1000_[0-9a-f]{4})\(([^)]*)\)\s*\n?"
    r"((?:[ \t]+[^\n;{]*;[ \t]*\n)*)\s*\{", re.M)


def _clean_ret(ret):
    ret = ret.replace("__cdecl16near", "").replace("__cdecl16far", "")
    ret = ret.replace("static", "").replace("inline", "")
    return " ".join(ret.split()) or "void"


def scan_text(text):
    out = {}
    for m in DEF_RE.finditer(text):
        ret, name, params, krdecls = m.groups()
        ret = _clean_ret(ret)
        if ret in ("return", "else", "do"):
            continue
        params = " ".join(params.split())
        if krdecls.strip():
            names = [p.strip() for p in params.split(",") if p.strip()]
            types = {}
            for d in krdecls.strip().split("\n"):
                d = d.strip().rstrip(";").strip()
                mm = re.match(r"(.*?)\b(\w+)$", d)
                if mm:
                    t = " ".join(mm.group(1).split())
                    types[mm.group(2)] = "int" if t in NARROW else t
            plist = [(types.get(n, "int"), n) for n in names]
        elif params in ("", "void"):
            plist = []
        else:
            plist = []
            for p in params.split(","):
                p = p.strip()
                mm = re.match(r"(.*?)\b(\w+)$", p)
                plist.append((" ".join(mm.group(1).split()), mm.group(2)))
        out[name] = (ret, plist)
    return out


def scan_files(files):
    defs = {}
    for f in files:
        try:
            defs.update(scan_text(open(f).read()))
        except FileNotFoundError:
            pass
    return defs


def write_header(defs, path):
    lines = ["/* Generated by gen_protos.py -- do not edit. */",
             "#ifndef SKYROADS_PROTOS_H", "#define SKYROADS_PROTOS_H",
             '#include "compat.h"', ""]
    for name in sorted(defs):
        ret, plist = defs[name]
        ps = ", ".join("%s %s" % (t, n) for t, n in plist) or "void"
        lines.append("%s %s(%s);" % (ret, name, ps))
    lines += ["", "#endif", ""]
    open(path, "w").write("\n".join(lines))


MANUAL_SOURCES = ["runtime.c", "manual.c", "render.c", "audio.c", "music.c", "hw.c", "video.c"]

if __name__ == "__main__":
    files = sys.argv[1:] or MANUAL_SOURCES + ["game.c"]
    d = scan_files(files)
    write_header(d, "protos.h")
    print("wrote protos.h (%d prototypes)" % len(d))
